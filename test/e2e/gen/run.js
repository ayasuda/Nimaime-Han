// End-to-end test of nimaime-gen (npm run test:e2e:gen): runs the built CLI (dist/) on this
// project, then `playwright test` on the generated specs, and checks the outcome:
// every test passes except the one of specs/failing/broken-on-purpose.sanmaime, which must fail
// with a Sanmaime failure message. specs/hooks.sanmaime passes only if the hooks of
// definitions/hooks.ts run (they open the page and check their own order). Then checks tags:
// `nimaime-gen export --tags @smoke` and `playwright test --grep @smoke` select exactly the tests
// of specs/tagged.sanmaime. specs/background.sanmaime passes only if the Background: and
// And when: conditions of definitions/background.ts run in order. specs/vocabulary.sanmaime uses
// every keyword of the expectation vocabulary v1 (Text:, Count:, Check, Focus, …).
//
// Needs `npm run build` first (the npm script does it): the CLI and the `nimaime-han` imports of
// the generated specs and definitions resolve to dist/.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';

const here = import.meta.dirname;
const root = path.resolve(here, '..', '..', '..');
const cli = path.join(root, 'dist', 'cli', 'nimaime-gen.js');
const config = path.relative(root, path.join(here, 'playwright.config.ts'));
const outputDir = path.join(here, '.sanmaime-gen');
const playwrightCli = createRequire(import.meta.url).resolve('@playwright/test/cli');

const TAGGED = [
  'Screen: Tagged Login > Element: Login Form > Always',
  'Screen: Tagged Login > Element: Login Button > When: The tags are known',
];
const EXPECTED_PASSED = [
  'Screen: Login > Element: Login Form > Always',
  'Screen: Login > Element: Login Button > When: Input is valid',
  'Screen: Login > Element: Login Button > When: Input is invalid',
  'Screen: ユーザー詳細 > Element: ユーザー情報 > Always',
  'Screen: ユーザー詳細 > Element: ユーザー情報 > When: 自分のプロフィールを閲覧している',
  'Screen: ユーザー詳細 > Element: ユーザー情報 > When: 他のユーザーのプロフィールを閲覧している',
  'Screen: ユーザー詳細 > Element: 編集ボタン > When: 自分のプロフィールを閲覧している',
  'Screen: ユーザー詳細 > Element: 編集ボタン > When: 他のユーザーのプロフィールを閲覧している',
  'Screen: Hooked Login > Element: Login Button > When: The hooks filled in the form',
  'Screen: Hooked Login > Element: Login Button > When: Email is cleared',
  'Screen: Composed Login > Element: Login Form > Always',
  'Screen: Composed Login > Element: Login Button > When: The order is checked',
  'Screen: Composed Login > Element: Login Button > When: The email is cleared and The order is checked',
  'Screen: Preferences > Element: Preferences Form > Always',
  'Screen: Preferences > Element: Preferences Form > When: The newsletter is chosen',
  'Screen: Preferences > Element: Newsletter Checkbox > Always',
  'Screen: Preferences > Element: Newsletter Checkbox > When: The newsletter is chosen',
  'Screen: Preferences > Element: Email Field > Always',
  'Screen: Preferences > Element: Email Field > When: The email field is clicked',
  ...TAGGED,
];
const EXPECTED_FAILED = ['Screen: Login > Element: Login Button > When: Input is valid'];

let failures = 0;
function check(condition, message) {
  if (condition) {
    console.log(`  ok  ${message}`);
  } else {
    failures++;
    console.error(`  FAIL ${message}`);
  }
}

function run(args, env = {}) {
  const result = spawnSync(process.execPath, args, {
    cwd: root,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
  if (result.error) throw result.error;
  return result;
}

if (!fs.existsSync(cli)) {
  console.error(`${cli} not found: run "npm run build" first.`);
  process.exit(1);
}

console.log(`nimaime-gen -c ${config}`);
const gen = run([cli, '-c', config]);
process.stdout.write(gen.stdout);
process.stderr.write(gen.stderr);
check(gen.status === 0, 'nimaime-gen exits with 0');
check(
  /^Generated 7 spec files \(22 tests\) into /.test(gen.stdout),
  'nimaime-gen prints a summary',
);
for (const file of [
  'login.spec.ts',
  'tagged.spec.ts',
  'ja/user-details.spec.ts',
  'failing/broken-on-purpose.spec.ts',
  'hooks.spec.ts',
  'background.spec.ts',
  'vocabulary.spec.ts',
]) {
  const generated = path.join(outputDir, 'specs', file);
  check(
    fs.existsSync(generated) &&
      fs.readFileSync(generated, 'utf8').startsWith('// Generated by nimaime-gen from specs/'),
    `generated ${path.relative(root, generated)}`,
  );
}

const hooksSpec = fs.readFileSync(path.join(outputDir, 'specs', 'hooks.spec.ts'), 'utf8');
check(
  hooksSpec.includes(`import { createNimaimeTest, runHooks } from 'nimaime-han/runtime';`) &&
    hooksSpec.includes(`test.beforeAll(async ({ browser }) => {`) &&
    hooksSpec.includes(`test.afterAll(async ({ browser }) => {`) &&
    hooksSpec.includes(`test.beforeEach(async ({ loginHtml, page }) => {`) &&
    hooksSpec.includes(`test.afterEach(async ({}) => {`),
  'hooks are generated as test.beforeAll / afterAll / beforeEach / afterEach',
);

const backgroundSpec = fs.readFileSync(path.join(outputDir, 'specs', 'background.spec.ts'), 'utf8');
check(
  backgroundSpec.includes(`background: ['The order log is started', 'A valid email is typed'],`) &&
    backgroundSpec.includes(`conditions: ['The email is cleared', 'The order is checked'],`),
  'Background: and And when: are generated as background / conditions',
);

const vocabularySpec = fs.readFileSync(path.join(outputDir, 'specs', 'vocabulary.spec.ts'), 'utf8');
check(
  vocabularySpec.includes(`value: 'Preferences',`) &&
    vocabularySpec.includes(`{ kind: 'count', target: 'Topics', value: 3, location:`) &&
    vocabularySpec.includes(`{ kind: 'check', target: 'Remember me', location:`) &&
    vocabularySpec.includes(`{ kind: 'focus', location:`),
  'the vocabulary v1 is generated as kind / target / value',
);

console.log(`\nplaywright test -c ${config}`);
const report = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'nimaime-e2e-')), 'report.json');
const pw = run([playwrightCli, 'test', '-c', config, '--reporter=json'], {
  PLAYWRIGHT_JSON_OUTPUT_FILE: report,
});
check(
  pw.status === 1,
  `playwright test exits with 1 (one test fails on purpose); got ${pw.status}`,
);
if (!fs.existsSync(report)) {
  process.stdout.write(pw.stdout);
  process.stderr.write(pw.stderr);
  console.error('No JSON report was written.');
  process.exit(1);
}

/** Flattens the JSON report into { title, file, status, errors }. */
function collect(suite, titles = [], out = []) {
  const path_ =
    suite.title && !suite.title.endsWith('.spec.ts') ? [...titles, suite.title] : titles;
  for (const spec of suite.specs ?? []) {
    for (const test of spec.tests) {
      const last = test.results.at(-1);
      out.push({
        title: [...path_, spec.title].join(' > '),
        file: spec.file,
        status: last?.status,
        errors: last?.errors ?? [],
      });
    }
  }
  for (const child of suite.suites ?? []) collect(child, path_, out);
  return out;
}

const json = JSON.parse(fs.readFileSync(report, 'utf8'));
const tests = json.suites.flatMap((suite) => collect(suite));
const passed = tests.filter((t) => t.status === 'passed');
const failed = tests.filter((t) => t.status !== 'passed');
check(tests.length === 22, `22 tests ran (got ${tests.length})`);
check(
  JSON.stringify(passed.map((t) => t.title).sort()) === JSON.stringify([...EXPECTED_PASSED].sort()),
  `the expected tests passed: ${passed.map((t) => t.title).join(' | ')}`,
);
check(
  JSON.stringify(failed.map((t) => t.title)) === JSON.stringify(EXPECTED_FAILED) &&
    failed[0]?.file.includes('broken-on-purpose.spec.ts'),
  `only broken-on-purpose fails: ${failed.map((t) => `${t.file}: ${t.title}`).join(' | ')}`,
);
const message = failed[0]?.errors.map((e) => e.message ?? '').join('\n') ?? '';
check(
  /Screen: Login/.test(message) &&
    /Element: Login Button/.test(message) &&
    /When: Input is valid/.test(message) &&
    /broken-on-purpose\.sanmaime:7/.test(message),
  'the failure carries the Sanmaime header and the .sanmaime location',
);
check(/toBeDisabled/.test(message), "the failure includes Playwright's assertion");

console.log(`\nnimaime-gen export -c ${config} --tags @smoke`);
const exported = run([cli, 'export', '-c', config, '--tags', '@smoke']);
process.stdout.write(exported.stdout);
process.stderr.write(exported.stderr);
check(
  exported.status === 0 &&
    exported.stdout ===
      [
        'test/e2e/gen/specs/tagged.sanmaime',
        ...TAGGED.map((title, i) => `  ${title}  @smoke${i === 1 ? ' @tagged @uses-tags' : ''}`),
        '2 tests in 1 spec file.',
        '',
      ].join('\n'),
  'nimaime-gen export --tags @smoke lists only the tagged tests, with their tags',
);

console.log(`\nplaywright test -c ${config} --grep @smoke`);
const grepReport = path.join(path.dirname(report), 'grep.json');
const grep = run([playwrightCli, 'test', '-c', config, '--grep', '@smoke', '--reporter=json'], {
  PLAYWRIGHT_JSON_OUTPUT_FILE: grepReport,
});
check(grep.status === 0, `playwright test --grep @smoke exits with 0; got ${grep.status}`);
const grepTests = fs.existsSync(grepReport)
  ? JSON.parse(fs.readFileSync(grepReport, 'utf8')).suites.flatMap((suite) => collect(suite))
  : [];
check(
  JSON.stringify(grepTests.map((t) => t.title).sort()) === JSON.stringify([...TAGGED].sort()) &&
    grepTests.every((t) => t.status === 'passed'),
  `--grep @smoke runs only the tagged tests, which pass: ${grepTests.map((t) => `${t.title} (${t.status})`).join(' | ')}`,
);

if (failures > 0) {
  console.error(`\n${failures} check(s) failed.`);
  if (failed.length > 0) console.error(message);
  process.exit(1);
}
console.log('\nAll nimaime-gen end-to-end checks passed.');
